import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {setupAccount,loadTabletSettings,saveTabletSettings} from '../shared.js';
const memory=new Map();globalThis.localStorage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
const nodes=new Map();for(const id of ['demo-room','settings-submit','settings-pin-label','settings-grid','live-login','email','password','logout','login-help','account','settings-pin','login-error','login-dialog','close-login','login-form','connection'])nodes.set(id,{value:'',focus(){},close(){},showModal(){},querySelector(){return nodes.get('settings-submit');}});
globalThis.document={getElementById:id=>nodes.get(id)||null,createElement:()=>({className:'',textContent:'',remove(){}}),body:{append(){}}};
let prepared=0,committed=0,fail=false;
const store={page:'patient',demo:false,profile:{room:'201'},async init(cb){cb(this.profile);},async changeRoom(room){assert.equal(room,'201');if(fail)throw Error('Save failed');}};
await setupAccount(store,()=>{},{prepareSettingsSave:()=>{prepared++;return ()=>{committed++;saveTabletSettings({...loadTabletSettings(),ward:'East ward'});};}})();
assert.equal(nodes.get('demo-room').readOnly,true,'room stays readonly even without label id');
const submit=()=>nodes.get('login-form').onsubmit({preventDefault(){},target:nodes.get('login-form')});
nodes.get('settings-pin').value='wrong';await submit();assert.equal(prepared,0);assert.match(nodes.get('login-error').textContent,/Incorrect PIN/);
nodes.get('settings-pin').value='1234';await submit();assert.equal(prepared,0,'unlock must not save');
fail=true;await submit();assert.equal(committed,0,'failed validation must not save');
fail=false;await submit();assert.equal(committed,1);assert.equal(loadTabletSettings().ward,'East ward','ward persists in device storage');
console.log('Passed: room readonly, PIN gating, failed save protection, ward persistence.');
const nursing=readFileSync('nursing-bot.html','utf8');
assert.ok(!nursing.includes('id="emergency-note"'));
assert.ok(!nursing.includes('id="staff"'));
assert.ok(!nursing.includes('id="language-tabs"'));
assert.ok(readFileSync('nursing-bot.js','utf8').includes('Say the room number, department and request in any language.'));
process.exit(0);
